/**
 * Resolve an old WordPress path to its 301 redirect target, or null if the path
 * is not a known old WordPress post (e.g. it's a real new-site route).
 */
export function getWpRedirectTarget(pathname: string): string | null {
  let normalized: string;
  try {
    normalized = decodeURIComponent(pathname);
  } catch {
    normalized = pathname;
  }
  if (normalized.length > 1 && normalized.endsWith("/")) {
    normalized = normalized.slice(0, -1);
  }
  return WP_REDIRECTS[normalized] ?? null;
}
